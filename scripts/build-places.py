import json, sys
sys.stdout.reconfigure(encoding="utf-8")
STATES = {
 "DE": {"01":"Baden-Württemberg","02":"Bayern","03":"Bremen","04":"Hamburg","05":"Hessen","06":"Niedersachsen",
        "07":"Nordrhein-Westfalen","08":"Rheinland-Pfalz","09":"Saarland","10":"Schleswig-Holstein","11":"Brandenburg",
        "12":"Mecklenburg-Vorpommern","13":"Sachsen","14":"Sachsen-Anhalt","15":"Thüringen","16":"Berlin"},
 "AT": {"01":"Burgenland","02":"Kärnten","03":"Niederösterreich","04":"Oberösterreich","05":"Salzburg","06":"Steiermark",
        "07":"Tirol","08":"Vorarlberg","09":"Wien"},
 "CH": {"AG":"Aargau","AI":"Appenzell Innerrhoden","AR":"Appenzell Ausserrhoden","BE":"Bern","BL":"Basel-Landschaft",
        "BS":"Basel-Stadt","FR":"Freiburg","GE":"Genf","GL":"Glarus","GR":"Graubünden","JU":"Jura","LU":"Luzern",
        "NE":"Neuenburg","NW":"Nidwalden","OW":"Obwalden","SG":"St. Gallen","SH":"Schaffhausen","SO":"Solothurn",
        "SZ":"Schwyz","TG":"Thurgau","TI":"Tessin","UR":"Uri","VD":"Waadt","VS":"Wallis","ZG":"Zug","ZH":"Zürich"},
}
KEEP = {"PPL","PPLA","PPLA2","PPLA3","PPLA4","PPLC","PPLF","PPLG","PPLL","PPLS"}   # no PPLX (city districts)
out = {c: {} for c in STATES}
for line in open(sys.argv[1], encoding="utf-8"):
    f = line.rstrip("\n").split("\t")
    cc, code, adm = f[8], f[7], f[10]
    if cc not in STATES or code not in KEEP or adm not in STATES[cc]:
        continue
    out[cc].setdefault(STATES[cc][adm], []).append([f[1], round(float(f[4]), 3), round(float(f[5]), 3)])
for cc in out:
    for st in out[cc]:
        out[cc][st].sort(key=lambda x: x[0].lower())
    print(cc, sum(len(v) for v in out[cc].values()), "places in", len(out[cc]), "states;", "Hessen" in out[cc] and len(out[cc]["Hessen"]))
js = "/* Generated by scripts/build-places.py from GeoNames cities1000 (CC BY 4.0). */\nwindow.PLACES = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
open(sys.argv[2], "w", encoding="utf-8").write(js)
print("bytes", len(js.encode("utf-8")))
